-- 2.3 usuario ---------------------------------------------------------
CREATE TABLE usuario (
    idusuario     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR(255) NOT NULL,
    apellido      VARCHAR(255) NOT NULL,
    correo        VARCHAR(255) NOT NULL,
    telefono      VARCHAR(255),
    usuario       VARCHAR(255) NOT NULL,
    clave         VARCHAR(255) NOT NULL,
    fechaRegistro DATE         NOT NULL DEFAULT CURRENT_DATE,
    estado        VARCHAR(255) NOT NULL DEFAULT 'activo',
    CONSTRAINT pk_usuario        PRIMARY KEY (idusuario),
    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT uq_usuario_usuario UNIQUE (usuario),
    CONSTRAINT ck_usuario_correo CHECK (correo LIKE '%_@_%._%'),
    CONSTRAINT ck_usuario_estado CHECK (estado IN ('activo', 'inactivo', 'bloqueado'))
);

-- 2.7 pago ------------------------------------------------------------
CREATE TABLE pago (
    idpago     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fecha      DATE           NOT NULL DEFAULT CURRENT_DATE,
    hora       TIME           NOT NULL DEFAULT CURRENT_TIME,
    montoTotal NUMERIC(10, 2) NOT NULL,
    metodoPago VARCHAR(255)   NOT NULL,
    estado     VARCHAR(255)   NOT NULL DEFAULT 'pendiente',
    idusuario  BIGINT         NOT NULL,
    CONSTRAINT pk_pago            PRIMARY KEY (idpago),
    CONSTRAINT ck_pago_monto      CHECK (montoTotal > 0),
    CONSTRAINT ck_pago_metodo     CHECK (metodoPago IN ('tarjeta_credito', 'tarjeta_debito', 'transferencia', 'efectivo')),
    CONSTRAINT ck_pago_estado     CHECK (estado IN ('pendiente', 'completado', 'rechazado', 'reembolsado')),
    CONSTRAINT fk_pago_usuario    FOREIGN KEY (idusuario)
        REFERENCES usuario (idusuario)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- 2.8 tarifa ----------------------------------------------------------
CREATE TABLE tarifa (
    idtarifa  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    precio    NUMERIC(10, 2) NOT NULL,
    estado    VARCHAR(255)   NOT NULL DEFAULT 'disponible',
    idfuncion BIGINT         NOT NULL,
    idasiento BIGINT         NOT NULL,
    CONSTRAINT pk_tarifa          PRIMARY KEY (idtarifa),
    CONSTRAINT uq_tarifa_funcion_asiento UNIQUE (idfuncion, idasiento),
    CONSTRAINT ck_tarifa_precio   CHECK (precio > 0),
    CONSTRAINT ck_tarifa_estado   CHECK (estado IN ('disponible', 'reservado', 'vendido', 'inactivo')),
    CONSTRAINT fk_tarifa_funcion  FOREIGN KEY (idfuncion)
        REFERENCES funcion (idfuncion)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT fk_tarifa_asiento  FOREIGN KEY (idasiento)
        REFERENCES asiento (idasiento)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);
