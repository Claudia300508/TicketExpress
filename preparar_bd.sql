-- =====================================================================
-- TicketExpress+  |  Preparar la base de datos (tablas + datos de los CSV)
-- Ejecutar con SQL Shell (psql), conectada a la base "ticketexpress",
-- estando dentro de la carpeta del proyecto (la que contiene la carpeta CSV).
-- Se puede ejecutar varias veces: borra las tablas y las vuelve a crear.
-- =====================================================================
\set ON_ERROR_STOP on
\encoding UTF8
-- Los CSV traen fechas tipo 12/14/2025 (mes/dia/anio): se fuerza ese formato.
SET datestyle = 'ISO, MDY';

-- 0. Limpiar (orden inverso de dependencias) ---------------------------
DROP TABLE IF EXISTS tique, tarifa, pago, funcion, asiento, evento, usuario, recinto, categoria CASCADE;

-- 2. TABLAS (en orden lógico de dependencias) ---------------------------

-- 2.1 categoria -------------------------------------------------------
CREATE TABLE categoria (
    idcategoria BIGINT GENERATED BY DEFAULT AS IDENTITY,
    categoria   VARCHAR(255) NOT NULL,
    CONSTRAINT pk_categoria        PRIMARY KEY (idcategoria),
    CONSTRAINT uq_categoria_nombre UNIQUE (categoria),
    CONSTRAINT ck_categoria_nombre CHECK (length(trim(categoria)) > 0)
);

-- 2.2 recinto ---------------------------------------------------------
CREATE TABLE recinto (
    idrecinto      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR(255) NOT NULL,
    direccion      VARCHAR(255) NOT NULL,
    ciudad         VARCHAR(255) NOT NULL,
    capacidadTotal INT          NOT NULL,
    CONSTRAINT pk_recinto           PRIMARY KEY (idrecinto),
    CONSTRAINT ck_recinto_capacidad CHECK (capacidadTotal > 0)
);

-- 2.3 usuario ---------------------------------------------------------
CREATE TABLE usuario (
    idusuario     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR(255) NOT NULL,
    apellido      VARCHAR(255) NOT NULL,
    correo        VARCHAR(255) NOT NULL,
    telefono      VARCHAR(255),
    usuario       VARCHAR(255) NOT NULL,
    clave         VARCHAR(255) NOT NULL,
    fechaRegistro DATE         NOT NULL DEFAULT CURRENT_DATE,
    estado        VARCHAR(255) NOT NULL DEFAULT 'activo',
    CONSTRAINT pk_usuario        PRIMARY KEY (idusuario),
    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT uq_usuario_usuario UNIQUE (usuario),
    CONSTRAINT ck_usuario_correo CHECK (correo LIKE '%_@_%._%'),
    CONSTRAINT ck_usuario_estado CHECK (estado IN ('activo', 'inactivo', 'bloqueado'))
);

-- 2.4 evento ----------------------------------------------------------
CREATE TABLE evento (
    idevento    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(255) NOT NULL,
    descripcion VARCHAR(255),
    idcategoria BIGINT       NOT NULL,
    CONSTRAINT pk_evento           PRIMARY KEY (idevento),
    CONSTRAINT fk_evento_categoria FOREIGN KEY (idcategoria)
        REFERENCES categoria (idcategoria)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- 2.5 asiento ---------------------------------------------------------
CREATE TABLE asiento (
    idasiento BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fila      VARCHAR(255) NOT NULL,
    numero    VARCHAR(255) NOT NULL,
    zona      VARCHAR(255) NOT NULL,
    idrecinto BIGINT       NOT NULL,
    CONSTRAINT pk_asiento         PRIMARY KEY (idasiento),
    CONSTRAINT uq_asiento_ubicacion UNIQUE (idrecinto, fila, numero),
    CONSTRAINT fk_asiento_recinto FOREIGN KEY (idrecinto)
        REFERENCES recinto (idrecinto)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- 2.6 funcion ---------------------------------------------------------
CREATE TABLE funcion (
    idfuncion BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fecha     DATE         NOT NULL,
    hora      TIME         NOT NULL,
    idevento  BIGINT       NOT NULL,
    idrecinto BIGINT       NOT NULL,
    estado    VARCHAR(255) NOT NULL DEFAULT 'programada',
    CONSTRAINT pk_funcion         PRIMARY KEY (idfuncion),
    CONSTRAINT uq_funcion_horario UNIQUE (idrecinto, fecha, hora),
    CONSTRAINT ck_funcion_estado  CHECK (estado IN ('programada', 'en_venta', 'agotada', 'finalizada', 'cancelada')),
    CONSTRAINT fk_funcion_evento  FOREIGN KEY (idevento)
        REFERENCES evento (idevento)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT fk_funcion_recinto FOREIGN KEY (idrecinto)
        REFERENCES recinto (idrecinto)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- 2.7 pago ------------------------------------------------------------
CREATE TABLE pago (
    idpago     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fecha      DATE           NOT NULL DEFAULT CURRENT_DATE,
    hora       TIME           NOT NULL DEFAULT CURRENT_TIME,
    montoTotal NUMERIC(10, 2) NOT NULL,
    metodoPago VARCHAR(255)   NOT NULL,
    estado     VARCHAR(255)   NOT NULL DEFAULT 'pendiente',
    idusuario  BIGINT         NOT NULL,
    CONSTRAINT pk_pago            PRIMARY KEY (idpago),
    CONSTRAINT ck_pago_monto      CHECK (montoTotal > 0),
    CONSTRAINT ck_pago_metodo     CHECK (metodoPago IN ('tarjeta_credito', 'tarjeta_debito', 'transferencia', 'efectivo')),
    CONSTRAINT ck_pago_estado     CHECK (estado IN ('pendiente', 'completado', 'rechazado', 'reembolsado')),
    CONSTRAINT fk_pago_usuario    FOREIGN KEY (idusuario)
        REFERENCES usuario (idusuario)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- 2.8 tarifa ----------------------------------------------------------
CREATE TABLE tarifa (
    idtarifa  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    precio    NUMERIC(10, 2) NOT NULL,
    estado    VARCHAR(255)   NOT NULL DEFAULT 'disponible',
    idfuncion BIGINT         NOT NULL,
    idasiento BIGINT         NOT NULL,
    CONSTRAINT pk_tarifa          PRIMARY KEY (idtarifa),
    CONSTRAINT uq_tarifa_funcion_asiento UNIQUE (idfuncion, idasiento),
    CONSTRAINT ck_tarifa_precio   CHECK (precio > 0),
    CONSTRAINT ck_tarifa_estado   CHECK (estado IN ('disponible', 'reservado', 'vendido', 'inactivo')),
    CONSTRAINT fk_tarifa_funcion  FOREIGN KEY (idfuncion)
        REFERENCES funcion (idfuncion)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT fk_tarifa_asiento  FOREIGN KEY (idasiento)
        REFERENCES asiento (idasiento)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- 2.9 tique -----------------------------------------------------------
CREATE TABLE tique (
    idtique       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo        VARCHAR(255)   NOT NULL,
    preciopagado  NUMERIC(10, 2) NOT NULL,
    fechaemision  TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado        VARCHAR(255)   NOT NULL DEFAULT 'emitido',
    idprecio      BIGINT         NOT NULL,
    idpago        BIGINT         NOT NULL,
    idusuario     BIGINT         NOT NULL,
    CONSTRAINT pk_tique              PRIMARY KEY (idtique),
    CONSTRAINT uq_tique_codigo       UNIQUE (codigo),
    CONSTRAINT ck_tique_preciopagado CHECK (preciopagado >= 0),
    CONSTRAINT ck_tique_estado       CHECK (estado IN ('emitido', 'usado', 'cancelado', 'vencido')),
    CONSTRAINT fk_tique_tarifa       FOREIGN KEY (idprecio)
        REFERENCES tarifa (idtarifa)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT fk_tique_pago         FOREIGN KEY (idpago)
        REFERENCES pago (idpago)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT fk_tique_usuario      FOREIGN KEY (idusuario)
        REFERENCES usuario (idusuario)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


-- 3. Ajuste para los datos de Mockaroo ----------------------------------
-- categoria.csv trae nombres repetidos ("Teatro", "Deportes"), asi que se
-- quita la restriccion UNIQUE de categoria.categoria para poder cargarlos.
ALTER TABLE categoria DROP CONSTRAINT uq_categoria_nombre;

-- 4. Importar los CSV (en orden de dependencias) ------------------------
-- Las columnas se indican en el mismo orden en que vienen en cada CSV.
\copy categoria (idcategoria, categoria) FROM 'CSV/categoria.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy recinto (idrecinto, nombre, direccion, ciudad, capacidadTotal) FROM 'CSV/recinto.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy usuario (idusuario, nombre, apellido, correo, telefono, usuario, clave, fechaRegistro, estado) FROM 'CSV/usuario.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy evento (idevento, nombre, descripcion, idcategoria) FROM 'CSV/evento.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy asiento (idasiento, numero, fila, zona, idrecinto) FROM 'CSV/asiento.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy funcion (idfuncion, fecha, hora, idevento, idrecinto, estado) FROM 'CSV/funcion.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy pago (idpago, fecha, hora, montoTotal, metodoPago, estado, idusuario) FROM 'CSV/pago.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy tarifa (idtarifa, precio, estado, idfuncion, idasiento) FROM 'CSV/tarifa.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy tique (idtique, codigo, preciopagado, fechaemision, estado, idprecio, idpago, idusuario) FROM 'CSV/tique.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')

-- 5. Reajustar los contadores de ID (los CSV trajeron sus propios ID) ---
SELECT setval(pg_get_serial_sequence('categoria','idcategoria'), (SELECT MAX(idcategoria) FROM categoria));
SELECT setval(pg_get_serial_sequence('recinto','idrecinto'),     (SELECT MAX(idrecinto)   FROM recinto));
SELECT setval(pg_get_serial_sequence('usuario','idusuario'),     (SELECT MAX(idusuario)   FROM usuario));
SELECT setval(pg_get_serial_sequence('evento','idevento'),       (SELECT MAX(idevento)    FROM evento));
SELECT setval(pg_get_serial_sequence('asiento','idasiento'),     (SELECT MAX(idasiento)   FROM asiento));
SELECT setval(pg_get_serial_sequence('funcion','idfuncion'),     (SELECT MAX(idfuncion)   FROM funcion));
SELECT setval(pg_get_serial_sequence('pago','idpago'),           (SELECT MAX(idpago)      FROM pago));
SELECT setval(pg_get_serial_sequence('tarifa','idtarifa'),       (SELECT MAX(idtarifa)    FROM tarifa));
SELECT setval(pg_get_serial_sequence('tique','idtique'),         (SELECT MAX(idtique)     FROM tique));

-- 6. Comprobacion rapida -------------------------------------------------
SELECT 'categoria' AS tabla, COUNT(*) AS registros FROM categoria
UNION ALL SELECT 'recinto', COUNT(*) FROM recinto
UNION ALL SELECT 'usuario', COUNT(*) FROM usuario
UNION ALL SELECT 'evento',  COUNT(*) FROM evento
UNION ALL SELECT 'asiento', COUNT(*) FROM asiento
UNION ALL SELECT 'funcion', COUNT(*) FROM funcion
UNION ALL SELECT 'pago',    COUNT(*) FROM pago
UNION ALL SELECT 'tarifa',  COUNT(*) FROM tarifa
UNION ALL SELECT 'tique',   COUNT(*) FROM tique;
